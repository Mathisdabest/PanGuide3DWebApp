"""Three-minute browser capture of actual saved model outputs, without fake inference."""
from pathlib import Path
import time, math
from playwright.sync_api import sync_playwright
out=Path('recordings/full-demo');out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch()
    context=browser.new_context(viewport={'width':1920,'height':1080},record_video_dir=str(out),record_video_size={'width':1920,'height':1080})
    page=context.new_page()
    page.goto('http://127.0.0.1:7860',wait_until='domcontentloaded',timeout=60000)
    page.get_by_role('button',name='Try Sample CT / Demo Mode').wait_for(timeout=60000)
    start=time.monotonic()
    def until(seconds):
        while time.monotonic()-start<seconds: page.wait_for_timeout(min(1000,max(1,(seconds-(time.monotonic()-start))*1000)))
    print('Capture: introduction',flush=True)
    until(18)
    page.get_by_label('I understand the limitations',exact=False).check()
    page.get_by_role('button',name='Try Sample CT / Demo Mode').scroll_into_view_if_needed()
    until(30)
    page.get_by_role('button',name='Try Sample CT / Demo Mode').click()
    page.wait_for_function("() => [...document.querySelectorAll('textarea,input')].some(e => e.value && e.value.includes('Ready ·'))",timeout=60000)
    print('Capture: actual cached masks loaded',flush=True)
    page.evaluate("""() => {const e=document.createElement('div');e.textContent='RECORDED MODEL OUTPUTS  •  RESEARCH & EDUCATIONAL USE ONLY';e.style='position:fixed;bottom:12px;left:50%;transform:translateX(-50%);padding:10px 22px;background:#102437ee;color:#bbebf3;border:1px solid #347187;border-radius:8px;z-index:10000;font:14px sans-serif;pointer-events:none';document.body.append(e)}""")
    until(58)
    page.locator('#axial-view').scroll_into_view_if_needed()
    page.screenshot(path=str(out/'01-orthogonal.png'))
    until(70)
    slider=page.locator('input[type=range]').nth(3)
    slider.focus(); slider.press('ArrowRight');page.wait_for_timeout(2000);slider.press('ArrowLeft')
    until(80)
    opacity=page.locator('input[type=range]').nth(2)
    opacity.focus()
    for _ in range(8): opacity.press('ArrowLeft')
    page.wait_for_timeout(1500)
    for _ in range(8): opacity.press('ArrowRight')
    until(92)
    print('Capture: 3D physical surfaces',flush=True)
    page.get_by_role('tab',name='3D Visualization',exact=True).click()
    page.locator('#anatomy3d').scroll_into_view_if_needed();page.wait_for_timeout(2000)
    box=page.locator('#anatomy3d canvas').first.bounding_box()
    if not box: raise RuntimeError('No 3D canvas; refusing a blank 3D recording')
    until(98)
    cx,cy=box['x']+box['width']*.48,box['y']+box['height']*.5
    page.mouse.move(cx-130,cy);page.mouse.down()
    for i in range(240):
        phase=i/239*math.pi*1.3
        page.mouse.move(cx-130+260*i/239,cy+35*math.sin(phase));page.wait_for_timeout(65)
    page.mouse.up()
    page.screenshot(path=str(out/'02-surfaces.png'))
    until(126)
    print('Capture: educational findings and export',flush=True)
    page.get_by_role('tab',name='AI Findings',exact=True).click()
    page.get_by_text('Tumor localization and review support',exact=True).scroll_into_view_if_needed()
    page.wait_for_timeout(2000);page.screenshot(path=str(out/'03-findings.png'))
    until(145)
    link=page.locator('a[href*="educational-report.pdf"]').first
    link.scroll_into_view_if_needed()
    with page.expect_download(timeout=15000) as download: link.click()
    download.value.save_as(out/'verified-browser-report.pdf')
    until(160)
    page.get_by_role('tab',name='About the Research',exact=True).click()
    page.get_by_text('Segmentation, with evidence and limits',exact=True).scroll_into_view_if_needed()
    until(174)
    page.evaluate('window.scrollTo({top:0,behavior:"smooth"})')
    until(180)
    video=page.video
    context.close()
    video.save_as(out/'PanGuide3D-browser-180s.webm')
    browser.close()
print('Capture complete: '+str((out/'PanGuide3D-browser-180s.webm').resolve()),flush=True)
